#Strings
# Strings is nothing but storing code is unicode

#Simple string
my_string = "Hello, World welcome to Python!"
print(my_string)

#String Concatenation
comb_string = "Hello, dude welcome to my " + "World!"
print(comb_string)

#String Slicing
print(my_string[0:5]) # Output: Hello

#String Substitution
new_string = "Hello, %s welcome to %s!"%("John", "Security")
new_string2 = "Hello, {0} welcome to {1}!".format("Sri", "Python")
print(new_string)
print(new_string2)

